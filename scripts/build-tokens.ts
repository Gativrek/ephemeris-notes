/**
 * `pnpm tokens`: generates the app's CSS variables from design/tokens.json (SPECS 14).
 * Names match design/components/bundle.css: `--<token>` and `--font-<family>`.
 * Light values go on :root, theme-dependent dark values on :root[data-theme="dark"].
 * A last block restores the light values inside any [data-theme="light"] element, so
 * light-only surfaces (the chooser, SPECS 7) ignore the app theme.
 *
 * Usage: node scripts/build-tokens.ts [--check]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type Themed = string | { light: string; dark: string };
interface Token {
  name: string;
  value: Themed;
}
interface TokenFile {
  color: { tokens: Token[] };
  type: { families: Record<string, string> };
  spacing: { tokens: Token[] };
  radius: { tokens: Token[] };
  size: { tokens: Token[] };
  shadow: { tokens: Token[] };
}

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = resolve(repo, 'design/tokens.json');
export const OUTPUT = resolve(repo, 'apps/desktop/src/renderer/styles/tokens.css');

const HEADER = '/* Generated by `pnpm tokens` from design/tokens.json (SPECS 14). Do not edit by hand. */\n';

function cssValue(v: string): string {
  // "{muted}" is an alias of another token.
  const alias = /^\{([a-z0-9-]+)\}$/.exec(v);
  return alias ? `var(--${alias[1]})` : v;
}

export function buildTokensCss(json: TokenFile): string {
  const light: string[] = [];
  const dark: string[] = [];
  const lightThemed: string[] = [];
  const add = (tokens: Token[]) => {
    for (const t of tokens) {
      if (typeof t.value === 'string') {
        light.push(`  --${t.name}: ${cssValue(t.value)};`);
      } else {
        light.push(`  --${t.name}: ${cssValue(t.value.light)};`);
        lightThemed.push(`  --${t.name}: ${cssValue(t.value.light)};`);
        dark.push(`  --${t.name}: ${cssValue(t.value.dark)};`);
      }
    }
  };
  add(json.color.tokens);
  for (const [family, stack] of Object.entries(json.type.families))
    light.push(`  --font-${family}: ${stack};`);
  add(json.spacing.tokens);
  add(json.radius.tokens);
  add(json.size.tokens);
  add(json.shadow.tokens);
  return (
    `:root {\n${light.join('\n')}\n}\n:root[data-theme="dark"] {\n${dark.join('\n')}\n}\n` +
    `[data-theme="light"] {\n${lightThemed.join('\n')}\n}\n`
  );
}

export function generate(): string {
  return HEADER + buildTokensCss(JSON.parse(readFileSync(SOURCE, 'utf8')) as TokenFile);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {
      // Missing counts as stale.
    }
    if (current !== css) {
      console.error('tokens.css is out of date. Run `pnpm tokens`.');
      process.exit(1);
    }
    console.log('tokens.css is up to date.');
  } else {
    mkdirSync(dirname(OUTPUT), { recursive: true });
    writeFileSync(OUTPUT, css);
    console.log(`Wrote ${OUTPUT}`);
  }
}
